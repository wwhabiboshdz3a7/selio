// Extracts the Phosphor "light"/"regular" SVG inner markup for the icons used by the ad into src/icons.js
const fs = require('fs'); const path = require('path');
const base = path.join(__dirname, 'node_modules/@phosphor-icons/core/assets');
const wanted = {
  light: ['t-shirt','dress','sneaker','handbag','coat-hanger','pants','baseball-cap','high-heel','boot','sunglasses','watch','backpack','hoodie','belt','shirt-folded','bag','shopping-bag','heart','chat-circle-dots','camera','sparkle','check','check-circle','tag','shield-check','lightning','users-three','robot','chart-line-up','file-xls','export','package','storefront','leaf','recycle','magnifying-glass','funnel','sliders-horizontal','bell','clock','device-mobile-camera','images','seal-check','arrow-right','swatches','hand-heart'],
  regular: ['heart','check','magnifying-glass','arrow-right','sliders-horizontal','funnel','camera','clock','lightning','file-xls','users-three','chart-line-up','coat-hanger','sparkle','check-circle','shield-check','device-mobile-camera','tag','chat-circle-dots','export','robot','package','storefront','bell','recycle','caret-down','calendar-check','paper-plane-right','moon-stars'],
  bold: ['check','arrow-right','clock','caret-down','paper-plane-right','x'],
  fill: ['heart','check-circle','sparkle','seal-check','lightning','star'],
};
const out = {};
for (const [weight, names] of Object.entries(wanted)) {
  for (const n of names) {
    const f = path.join(base, weight, `${n}${weight === 'regular' ? '' : '-' + weight}.svg`);
    if (!fs.existsSync(f)) { console.error('missing', f); continue; }
    const svg = fs.readFileSync(f, 'utf8');
    const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
    out[`${n}:${weight}`] = inner;
  }
}
fs.mkdirSync(path.join(__dirname, 'src'), { recursive: true });
fs.writeFileSync(path.join(__dirname, 'src/icons.js'), `// Generated by build-icons.cjs from @phosphor-icons/core (MIT). viewBox 0 0 256 256, fill=currentColor\nexport const ICONS = ${JSON.stringify(out)};\n`);
console.log('icons written:', Object.keys(out).length);
